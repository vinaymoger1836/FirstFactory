// Generates src/generated/ from the JSON Schema exported by packages/domain (docs/04 §1).
//
//   1. `uv run python -m fl_domain.schema` writes src/generated/domain.schema.json
//      (or FL_DOMAIN_SCHEMA points at a pre-built schema, e.g. in a Node-only CI step);
//   2. json-schema-to-typescript turns it into src/generated/index.ts.
//
// The output is git-ignored and rebuilt at build time (CLAUDE.md owner's rule 1). Never hand-edit.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(pkg, "..", "..");
const out = join(pkg, "src", "generated");
const schemaPath = process.env.FL_DOMAIN_SCHEMA ?? join(out, "domain.schema.json");
mkdirSync(out, { recursive: true });

if (!process.env.FL_DOMAIN_SCHEMA) {
  execFileSync(
    "uv",
    ["run", "--frozen", "python", "-m", "fl_domain.schema", "--out", schemaPath],
    { cwd: repo, stdio: ["ignore", "inherit", "inherit"] },
  );
}
if (!existsSync(schemaPath)) {
  throw new Error(`ts-types: schema not found at ${schemaPath}`);
}

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ts = await compile(schema, "FactoryDomain", {
  bannerComment:
    "/* GENERATED by packages/ts-types/scripts/generate.mjs from fl_domain.schema. Do not edit. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  declareExternallyReferenced: true,
});
writeFileSync(join(out, "index.ts"), ts);
const types = (ts.match(/^export (interface|type) /gm) ?? []).length;
console.log(`ts-types: wrote ${join(out, "index.ts")} (${types} exported types)`);
